#!/usr/bin/env bash
# Runs inside the Finima LXC.
#   First run (from install.sh): installs Docker, clones Finima to /opt/finima, generates secrets, starts it.
#   Later: `finima-update [version]` re-runs this to pull new code/images and restart.
set -euo pipefail
die(){ echo "ERROR: $*" >&2; exit 1; }
APP=/opt/finima
NEW_VERSION=${1:-}

if [[ -f $APP/.env ]]; then
  set -a; source "$APP/.env"; set +a
elif [[ -f /root/finima-install.env ]]; then
  source /root/finima-install.env
fi
REPO=${FINIMA_REPO:-https://github.com/Mcp20091/finima.git}
REF=${FINIMA_REF:-main}

echo "== Docker"
export DEBIAN_FRONTEND=noninteractive
if ! command -v docker >/dev/null; then
  apt-get update
  apt-get install -y ca-certificates curl git openssl
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/debian/gpg -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  cat > /etc/apt/sources.list.d/docker.sources <<SRC
Types: deb
URIs: https://download.docker.com/linux/debian
Suites: $(. /etc/os-release && echo "$VERSION_CODENAME")
Components: stable
Architectures: $(dpkg --print-architecture)
Signed-By: /etc/apt/keyrings/docker.asc
SRC
  apt-get update
  apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
fi
docker run --rm hello-world >/dev/null \
  || die "Docker can't run containers here. On the Proxmox host: pct config <id> | grep features  (needs nesting=1,keyctl=1)"

echo "== Code ($REPO @ $REF)"
if [[ -d $APP/.git ]]; then
  git -C "$APP" fetch -q origin
  git -C "$APP" checkout -q "$REF"
  git -C "$APP" pull -q --ff-only
else
  git clone -q --branch "$REF" "$REPO" "$APP"
fi
cd "$APP"

if [[ ! -f .env ]]; then
  echo "== Generating .env with random secrets"
  url=${FINIMA_URL:-http://$(hostname -I | awk '{print $1}')}
  llm=${FINIMA_LLM:-none}
  (umask 077; cat > .env <<ENV
# Generated by proxmox/setup.sh. Contains secrets - keep private. Format: KEY=VALUE, no quotes.
COMPOSE_FILE=docker-compose.prod.yml:proxmox/compose.proxmox.yml
COMPOSE_PROFILES=$([[ $llm == ollama ]] && echo ollama || true)
FINIMA_REF=$REF
FINIMA_VERSION=${FINIMA_VERSION:-0.2.0}
FINIMA_URL=$url
DOMAIN=${FINIMA_SITE:-:80}
FINIMA_LLM_PROVIDER=$llm
FINIMA_OLLAMA_MODEL=${FINIMA_OLLAMA_MODEL:-qwen3:4b}
POSTGRES_USER=finima
POSTGRES_DB=finima
POSTGRES_PASSWORD=$(openssl rand -hex 24)
MINIO_ROOT_USER=finima
MINIO_ROOT_PASSWORD=$(openssl rand -hex 24)
JWT_SECRET=$(openssl rand -hex 32)
RESEND_API_KEY=${RESEND_API_KEY:-}
BACKUP_RETENTION_DAYS=30
ENV
  )
  rm -f /root/finima-install.env
fi
[[ -n $NEW_VERSION ]] && sed -i "s/^FINIMA_VERSION=.*/FINIMA_VERSION=$NEW_VERSION/" .env
set -a; source .env; set +a

echo "== Config override"
mkdir -p proxmox/local
grep -q '^  allowed_origins: \[\]$' config/production.yaml \
  || die "config/production.yaml no longer has 'allowed_origins: []'; proxmox/setup.sh needs updating."
sed "s|^  allowed_origins: \[\]$|  allowed_origins: [\"$FINIMA_URL\"]|" config/production.yaml > proxmox/local/production.yaml

echo "== Starting Finima $FINIMA_VERSION"
docker compose pull -q
docker compose up -d --remove-orphans

if [[ $FINIMA_LLM_PROVIDER == ollama ]]; then
  echo "== Pulling Ollama model $FINIMA_OLLAMA_MODEL (several GB, first time only)"
  for i in {1..10}; do docker compose exec -T ollama ollama pull "$FINIMA_OLLAMA_MODEL" && break; sleep 3; done
fi

echo "== Waiting for backend health"
ip=$(docker inspect -f '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}' "$(docker compose ps -q backend)")
for i in {1..60}; do
  if health=$(curl -fsS "http://$ip:3000/health" 2>/dev/null); then echo "$health"; break; fi
  sleep 5
done
[[ -n ${health:-} ]] || die "Backend not healthy after 5 min. Check: cd $APP && docker compose logs backend"

# Helper commands
cat > /usr/local/bin/finima-update <<'CMD'
#!/usr/bin/env bash
# Usage: finima-update [version]   (copy first: git pull may rewrite setup.sh while it runs)
tmp=$(mktemp); cp /opt/finima/proxmox/setup.sh "$tmp"; exec bash "$tmp" "$@"
CMD
cat > /usr/local/bin/finima-login-link <<'CMD'
#!/usr/bin/env bash
# Without a Resend API key, magic sign-in links are written to the backend log instead of emailed.
cd /opt/finima && docker compose logs --no-log-prefix backend | grep 'Magic link for' | tail -1 | grep -oE 'https?://[^" ]+' | tail -1
CMD
chmod 755 /usr/local/bin/finima-update /usr/local/bin/finima-login-link

echo
echo "Finima is running at $FINIMA_URL"
[[ -z $RESEND_API_KEY ]] && echo "Sign in: request a link in the browser, then run 'finima-login-link' in this container."
